def test_row_counts_match_pipeline_output(conn):
    counts = {
        row[0]: row[1]
        for row in conn.execute(text("""
            SELECT 'machines', COUNT(*) FROM machines
            UNION ALL SELECT 'sensor_summary', COUNT(*) FROM sensor_summary
            UNION ALL SELECT 'machine_anomalies', COUNT(*) FROM machine_anomalies
            UNION ALL SELECT 'maintenance_records', COUNT(*) FROM maintenance_records
            UNION ALL SELECT 'ai4i_reference', COUNT(*) FROM ai4i_reference
        """)).fetchall()
    }
    assert counts["machines"] == 18
    assert counts["sensor_summary"] == 25920  # 18 machines x 1440 hourly windows
    # Audit F9: was 18,912 before the rolling-window fix (z-score
    # baseline previously included the point being tested, which
    # mathematically capped the z-score just above the anomaly threshold
    # and made the statistical layer almost inert). With the fix,
    # 28,855 rows is the real count from a re-run of the pipeline
    # against this same data (verified: HIGH severity rows went from 16
    # to 248 in the same re-run — the statistical layer now actually
    # contributes signal instead of noise).
    assert counts["machine_anomalies"] == 28855
    assert counts["maintenance_records"] == 7
    assert counts["ai4i_reference"] == 10000


def test_no_orphaned_foreign_keys(conn):
    """Every child-table machine_id must exist in machines — the FK
    constraints enforce this at write time, but confirm it holds for data
    that was already loaded via a bulk path that could bypass checks."""
    for table in ["sensor_summary", "machine_anomalies", "maintenance_records"]:
        orphans = conn.execute(text(f"""
            SELECT COUNT(*) FROM {table} t
            LEFT JOIN machines m
              ON m.tenant_id = t.tenant_id AND m.machine_id = t.machine_id
            WHERE m.machine_id IS NULL
        """)).scalar()
        assert orphans == 0, f"{table} has rows with no matching machine"


