def test_ai4i_failure_mode_rates_covers_all_five_modes(conn):
    """No hardcoded expected percentages here — those are a fact about
    the real published dataset, not this project's code — just the
    invariants get_ai4i_failure_mode_rates promises: all five AI4I codes
    present, rates bounded, and every mode's total_real_failures agrees
    (it's the same denominator query run once per mode)."""
    rates = get_ai4i_failure_mode_rates(conn)
    assert set(rates) == {"TWF", "HDF", "PWF", "OSF", "RNF"}
    total_failures = {stats["total_real_failures"] for stats in rates.values()}
    assert len(total_failures) == 1  # same denominator across all five modes
    for mode, stats in rates.items():
        assert stats["total_real_rows"] == 10000
        assert 0 <= stats["failure_count"] <= stats["total_real_failures"]
        assert 0 <= stats["share_of_real_failures"] <= 1


# ---------------------------------------------------------------------
# Index sanity check — confirm the planned composite index is actually
# used for the query pattern it was built for, not just present.
# ---------------------------------------------------------------------

def test_machine_window_query_uses_the_composite_index(conn):
    plan = conn.execute(text("""
        EXPLAIN SELECT * FROM sensor_summary
        WHERE tenant_id = 'default' AND machine_id = 'M-01'
          AND window_start >= '2026-02-01'
        ORDER BY window_start DESC LIMIT 10
    """)).fetchall()
    plan_text = "\n".join(row[0] for row in plan)
    # Postgres may plan this via the named idx_sensor_summary_machine_window
    # OR via the UNIQUE (tenant_id, machine_id, window_start) constraint's
    # own auto-created index — both cover the same three columns in the same
    # order, so either is the composite index doing its job (a sequential
    # scan is the failure mode this test guards against).
    assert "Index Scan" in plan_text
    assert "sensor_summary" in plan_text
    assert "Seq Scan" not in plan_text
