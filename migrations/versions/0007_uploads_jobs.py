"""Uploads, background jobs and rejected rows (Phase 3 of the self-serve platform).

  * uploads        - one row per file a tenant uploaded. The object key is
    generated by the server (tenants/<tenant_id>/uploads/<upload_id>/data.csv)
    and the confirmed column mapping is stored on the row (the older
    tenant_schema_mappings CHECK only allows 'operational'/'maintenance').
  * jobs           - the work queue AND its status. A Postgres-backed queue:
    workers claim rows with FOR UPDATE SKIP LOCKED through the SECURITY
    DEFINER function iia_claim_job() (cross-tenant by design; it returns only
    ids), then do everything else with the tenant context bound.
  * rejected_rows  - rows/cells a job refused, with a reason and the raw row.
  * RLS            - uploads and rejected_rows are FORCEd like every other
    tenant table. `jobs` is ENABLEd but not FORCEd: the claim/reap functions
    run as the table owner and must see every tenant's jobs; iia_app and
    iia_worker are not owners, so the tenant_isolation policy still binds them.
  * iia_worker     - a second least-privilege role (NOLOGIN here;
    scripts/provision_app_role.py sets LOGIN from WORKER_DB_PASSWORD). It gets
    the write grants the worker needs; iia_app stays read-mostly. Both roles'
    grants are (re)applied by iia_grant_app_privileges(), so restore_db.py
    needs no change.
  * machine_anomalies gets UNIQUE (tenant_id, machine_id, detected_at). Without
    it, re-running the same upload would insert every anomaly again. The
    upgrade refuses (with the offending count) if existing rows already
    violate it.
  * machines.production_line widens VARCHAR(20) -> VARCHAR(100): the mapping
    accepts any string there. (machine_id was already widened by 0005.)

Revision ID: 0007
Revises: 0006
"""
