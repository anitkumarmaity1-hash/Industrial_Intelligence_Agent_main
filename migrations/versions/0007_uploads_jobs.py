def _run(sql: str) -> None:
    # Raw driver SQL (no text() bind parsing); psycopg2 needs literal % doubled.
    op.get_bind().exec_driver_sql(sql.replace("%", "%%"))


def upgrade() -> None:
    conn = op.get_bind()
    dupes = conn.exec_driver_sql(
        "SELECT COUNT(*) FROM (SELECT 1 FROM machine_anomalies "
        "GROUP BY tenant_id, machine_id, detected_at HAVING COUNT(*) > 1) d").scalar()
    if dupes:
        raise RuntimeError(
            f"Refusing to upgrade: {dupes} (tenant, machine, detected_at) group(s) in "
            "machine_anomalies hold more than one row, so UNIQUE (tenant_id, machine_id, "
            "detected_at) cannot be added. De-duplicate them first.")

    _run("ALTER TABLE machines ALTER COLUMN production_line TYPE VARCHAR(100)")
    _run("ALTER TABLE machine_anomalies ADD CONSTRAINT uq_machine_anomalies_tenant_machine_detected "
         "UNIQUE (tenant_id, machine_id, detected_at)")
    _run(_TABLES)
    _run(_CLAIM_FNS)
    _run("SELECT iia_enable_tenant_rls('uploads')")
    _run("SELECT iia_enable_tenant_rls('rejected_rows')")
    # jobs: ENABLE only (see module docstring); same policy text as iia_enable_tenant_rls.
    _run("ALTER TABLE jobs ENABLE ROW LEVEL SECURITY")
    _run("CREATE POLICY tenant_isolation ON jobs "
         "USING (tenant_id = NULLIF(current_setting('app.tenant_id', true), '')) "
         "WITH CHECK (tenant_id = NULLIF(current_setting('app.tenant_id', true), ''))")
    _run(_GRANT_FN)
    _run("SELECT iia_grant_app_privileges()")


def downgrade() -> None:
    conn = op.get_bind()
    stored = conn.exec_driver_sql(
        "SELECT (SELECT COUNT(*) FROM uploads) + (SELECT COUNT(*) FROM jobs)").scalar()
    if stored:
        raise RuntimeError(
            f"Refusing to downgrade: {stored} upload/job row(s) would be dropped with the "
            "uploads, jobs and rejected_rows tables. Export or delete them first.")
    too_long = conn.exec_driver_sql(
        "SELECT COUNT(*) FROM machines WHERE length(production_line) > 20").scalar()
    if too_long:
        raise RuntimeError(
            f"Refusing to downgrade: {too_long} machine(s) have a production_line longer than "
            "20 characters, which the previous schema cannot hold.")

    _run("""
        DO $$ BEGIN
            IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'iia_worker') THEN
                REVOKE ALL ON ALL TABLES IN SCHEMA public FROM iia_worker;
                REVOKE ALL ON ALL SEQUENCES IN SCHEMA public FROM iia_worker;
                REVOKE ALL ON FUNCTION iia_claim_job() FROM iia_worker;
                REVOKE ALL ON FUNCTION iia_reap_stale_jobs(integer) FROM iia_worker;
                REVOKE ALL ON SCHEMA public FROM iia_worker;
            END IF;
        END $$
    """)
    _run("DROP TABLE rejected_rows")
    _run("DROP TABLE jobs")
    _run("DROP TABLE uploads")
    _run("DROP FUNCTION iia_reap_stale_jobs(integer)")
    _run("DROP FUNCTION iia_claim_job()")
    _run("ALTER TABLE machine_anomalies DROP CONSTRAINT uq_machine_anomalies_tenant_machine_detected")
    _run("ALTER TABLE machines ALTER COLUMN production_line TYPE VARCHAR(20)")
    _run(_GRANT_FN_0006)
    _run("SELECT iia_grant_app_privileges()")
